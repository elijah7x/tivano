"""Outline the badge's text into SVG path data, so the badge needs no installed fonts.

Needs fontTools and uharfbuzz (run it with a venv that has them). Writes
text_outlines.py, which final.py imports with the standard library only.
Fonts are SIL OFL 1.1: Cinzel (titles) and Cormorant Garamond (the motto).
"""
import json
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).parent
FONTS = {
    'cinzel': (HERE / 'fonts/Cinzel.ttf', 500),
    'cormorant': (HERE / 'fonts/Cormorant.ttf', 500),
}
# key: (font, text, tracking in em)
TEXTS = {
    'title': ('cinzel', 'EARLY SUPPORTER', .10),
    'thanks': ('cinzel', 'WITH THANKS FOR USING AND SUPPORTING TIVANO', .16),
    'footer': ('cinzel', 'TIVANO · ELIJAH', .22),
    'motto1': ('cormorant', 'May intelligence enrich imagination,', .01),
    'motto2': ('cormorant', 'create the future,', .01),
    'motto3': ('cormorant', 'and benefit humankind.', .01),
}

loaded = {}
for name, (path, weight) in FONTS.items():
    data = path.read_bytes()
    face = hb.Face(data)
    font = hb.Font(face)
    font.set_variations({'wght': weight})
    static = instantiateVariableFont(TTFont(path), {'wght': weight})
    loaded[name] = (font, static, face.upem)

out = {}
for key, (name, text, tracking) in TEXTS.items():
    font, static, upem = loaded[name]
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {'kern': True, 'liga': True})
    glyphs = static.getGlyphSet()
    order = static.getGlyphOrder()
    pen = SVGPathPen(glyphs)
    x = 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        glyph = order[info.codepoint]
        # Flip y: font units grow upward, SVG grows downward; baseline at y=0.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
        x += pos.x_advance + tracking * upem
    width = x - tracking * upem
    out[key] = {'d': pen.getCommands(), 'width': width, 'upem': upem}

(HERE / 'text_outlines.py').write_text(
    '# Generated by outline_text.py from SIL OFL fonts; do not edit.\nOUTLINES = ' + json.dumps(out) + '\n',
    encoding='utf-8')
print({k: round(v['width'] / v['upem'], 2) for k, v in out.items()})
